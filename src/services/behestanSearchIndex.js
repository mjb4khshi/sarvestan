/** فقط کدهایی که واقعاً در سروستان پیاده شده‌اند، tab دارند */
export const DASHBOARD_CODE_TABS = {
  '79': 'transcripts',
  '78': 'schedule',
  '88': 'schedule',
  '428': 'schedule',
  '27570': 'finance',
  '2563': 'finance',
  '1965': 'finance',
  '11126': 'curriculum',
  '21122': 'requests',
  '6524': 'requests',
  '11122': 'letters',
  '11147': 'overview'
};

export function getDashboardTabForCode(code) {
  return DASHBOARD_CODE_TABS[String(code || '').trim()] || null;
}

export function searchBehestanIndex(query, limit = 10) {
  const q = normalizeQuery(query);
  if (!q) return [];

  const matched = [];

  for (const item of BEHESTAN_SEARCH_INDEX) {
    const codeNorm = normalizeQuery(item.code);
    const titleNorm = normalizeQuery(item.title);
    const keywordsNorm = (item.keywords || []).map(normalizeQuery);

    const isCodeMatch = codeNorm === q || codeNorm.startsWith(q) || codeNorm.includes(q);
    const isTitleMatch = titleNorm.includes(q);
    const isKeywordMatch = keywordsNorm.some(k => k.includes(q) || q.includes(k));

    if (isCodeMatch || isTitleMatch || isKeywordMatch) {
      let score = 0;
      if (codeNorm === q) score += 100;
      else if (codeNorm.startsWith(q)) score += 80;
      else if (isKeywordMatch) score += 60;
      else if (titleNorm.startsWith(q)) score += 50;
      else score += 30;

      // tab فقط از لیست مجاز — ایندکس خام ممکن است tab اشتباه داشته باشد
      const safeTab = getDashboardTabForCode(item.code);
      if (safeTab) score += 15;

      matched.push({
        item: { ...item, tab: safeTab },
        score
      });
    }
  }

  matched.sort((a, b) => b.score - a.score);
  return matched.slice(0, limit).map(m => m.item);
}
